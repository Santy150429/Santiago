def sumara_numeros(numero1,numero2):
    suma=numero1+numero2
    print(f"La suma de {numero1} + {numero2} = {suma}")
    return suma

#Funcion para dividir
def dividir_numeros(numero3,numero4):
    total=numero3/numero4
    print(f"La divicion entre {numero3} / {numero4} = {total}")
    return total

#funcion para multiplicar
def multiplicar_numeros(numero5,numero6):
    multiplicacion=numero5*numero6
    print(f"La multiplicacion de {numero5} * {numero6} = {multiplicacion}")
    return multiplicacion

#Funcion para restar
def restar_numeros(numero7,numero8):
    resta=numero7-numero8
    print(f"La resta de {numero7} - {numero8} = {resta}")
    return resta